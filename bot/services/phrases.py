def get_random_winner_roast(user_name: Optional[str] = None) -> str:
    """Return a random roast for the monthly winner."""
    roast = random.choice(WINNER_ROASTS)
    if user_name and random.random() < 0.3:
        return f"{user_name}, {roast.lower()}"
    return roast


def get_random_winner_drink_roast() -> str:
    """Return a roast when the monthly winner logs more alcohol."""
    return random.choice(WINNER_DRINKING_ROASTS)


def get_random_drink_comment() -> str:
    """Return an encouraging/ironic comment on logging a drink."""
    return random.choice(ORDINARY_DRINK_COMMENTS)

